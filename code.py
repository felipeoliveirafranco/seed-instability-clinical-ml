# Hyperparameter Optimization Engine
def optimize_algorithm(model_name, imp_name, X_tr, y_tr, current_seed, is_native=False, use_cv=True):
    cv_inner = StratifiedKFold(n_splits=5, shuffle=True, random_state=current_seed)

    if not is_native:
        pipeline_prep = Pipeline([('prep', get_classic_preprocessor(imp_name, current_seed)), ('corr_drop', CorrelationDropper(threshold=0.85))])
        X_opt = sanitize_feature_names(pipeline_prep.fit_transform(X_tr))
    else:
        X_opt = X_tr

    if not use_cv:
        X_sub_tr, X_val, y_sub_tr, y_val = train_test_split(X_opt, y_tr, test_size=0.25, random_state=current_seed, stratify=y_tr)

    def objective(trial):
        try:
            if is_native:
                if model_name == 'CATB_Native': clf = CatBoostClassifier(iterations=trial.suggest_categorical('iterations', [30, 50]), depth=trial.suggest_categorical('depth', [2, 3]), learning_rate=trial.suggest_categorical('learning_rate', [0.01, 0.05]), l2_leaf_reg=trial.suggest_categorical('l2_leaf_reg', [1.0, 3.0, 5.0]), random_state=current_seed, verbose=False, cat_features=cat_cols, auto_class_weights='Balanced')
                elif model_name == 'LGBM_Native': clf = LGBMClassifier(n_estimators=trial.suggest_categorical('n_estimators', [30, 50]), max_depth=trial.suggest_categorical('max_depth', [2, 3]), learning_rate=trial.suggest_categorical('learning_rate', [0.01, 0.05]), num_leaves=trial.suggest_categorical('num_leaves', [4, 7]), min_child_samples=trial.suggest_categorical('min_child_samples', [2, 5]), verbose=-1, random_state=current_seed, is_unbalance=True)
                elif model_name == 'XGB_Native': clf = XGBClassifier(n_estimators=trial.suggest_categorical('n_estimators', [30, 50]), max_depth=trial.suggest_categorical('max_depth', [2, 3]), learning_rate=trial.suggest_categorical('learning_rate', [0.01, 0.05]), subsample=trial.suggest_categorical('subsample', [0.8, 1.0]), colsample_bytree=trial.suggest_categorical('colsample_bytree', [0.8, 1.0]), enable_categorical=True, tree_method='hist', random_state=current_seed)

                if use_cv:
                    scores = []
                    for tr_idx, val_idx in cv_inner.split(X_opt, y_tr):
                        X_f_tr, X_f_val = X_opt.iloc[tr_idx], X_opt.iloc[val_idx]
                        y_f_tr, y_f_val = y_tr.iloc[tr_idx], y_tr.iloc[val_idx]
                        with HiddenPrints(): clf.fit(X_f_tr, y_f_tr)
                        scores.append(roc_auc_score(y_f_val, clf.predict_proba(X_f_val)[:, 1]))
                    return np.mean(scores)
                else:
                    with HiddenPrints(): clf.fit(X_sub_tr, y_sub_tr)
                    return roc_auc_score(y_val, clf.predict_proba(X_val)[:, 1])
            else:
                max_avail = X_opt.shape[1]
                n_features = trial.suggest_int('n_features', min(5, max_avail), max_avail)

                if model_name == 'LR': clf = LogisticRegression(penalty=trial.suggest_categorical('penalty', ['l1', 'l2']), C=trial.suggest_categorical('C', [0.1, 1.0, 5.0]), solver='liblinear', class_weight='balanced', random_state=current_seed)
                elif model_name == 'RF': clf = RandomForestClassifier(n_estimators=trial.suggest_categorical('n_estimators', [30, 50]), max_depth=trial.suggest_categorical('max_depth', [2, 3]), min_samples_split=trial.suggest_categorical('min_samples_split', [2, 5]), class_weight='balanced', random_state=current_seed)
                elif model_name == 'SVM': clf = SVC(C=trial.suggest_categorical('C', [0.1, 1.0, 5.0]), kernel=trial.suggest_categorical('kernel', ['linear', 'rbf']), probability=True, class_weight='balanced', random_state=current_seed)
                elif model_name == 'XGB': clf = XGBClassifier(n_estimators=trial.suggest_categorical('n_estimators', [30, 50]), max_depth=trial.suggest_categorical('max_depth', [2, 3]), learning_rate=trial.suggest_categorical('learning_rate', [0.01, 0.05]), subsample=trial.suggest_categorical('subsample', [0.8, 1.0]), eval_metric='logloss', random_state=current_seed)
                elif model_name == 'LGBM': clf = LGBMClassifier(n_estimators=trial.suggest_categorical('n_estimators', [30, 50]), max_depth=trial.suggest_categorical('max_depth', [2, 3]), learning_rate=trial.suggest_categorical('learning_rate', [0.01, 0.05]), num_leaves=trial.suggest_categorical('num_leaves', [4, 7]), min_child_samples=trial.suggest_categorical('min_child_samples', [2, 5]), verbose=-1, is_unbalance=True, random_state=current_seed)
                elif model_name == 'CATB': clf = CatBoostClassifier(iterations=trial.suggest_categorical('iterations', [30, 50]), depth=trial.suggest_categorical('depth', [2, 3]), learning_rate=trial.suggest_categorical('learning_rate', [0.01, 0.05]), l2_leaf_reg=trial.suggest_categorical('l2_leaf_reg', [1.0, 3.0, 5.0]), random_state=current_seed, verbose=False, auto_class_weights='Balanced')

                selector = SelectFromModel(RandomForestClassifier(n_estimators=50, max_depth=3, class_weight='balanced', random_state=current_seed), max_features=n_features, threshold=-np.inf)

                if use_cv:
                    pipe_eval = Pipeline([('feat_sel', selector), ('clf', clf)])
                    with HiddenPrints(): return np.mean(cross_val_score(pipe_eval, X_opt, y_tr, cv=cv_inner, scoring='roc_auc'))
                else:
                    X_sub_tr_f = selector.fit_transform(X_sub_tr, y_sub_tr)
                    X_val_f = selector.transform(X_val)
                    with HiddenPrints(): clf.fit(X_sub_tr_f, y_sub_tr)
                    return roc_auc_score(y_val, clf.predict_proba(X_val_f)[:, 1])

        except Exception: return 0.5

    study = optuna.create_study(direction='maximize', sampler=optuna.samplers.TPESampler(seed=current_seed))
    study.optimize(objective, n_trials=20)
    try: return study.best_params, study.best_value
    except ValueError: return None, None

