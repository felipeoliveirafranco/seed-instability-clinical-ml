from scipy.optimize import curve_fit

def power_law(x, a, b): return a * (x ** b)

def interpolate_n(x_data, y_data, target_sd):
    try:
        a, b = curve_fit(power_law, x_data, y_data, maxfev=10000)[0]
        calc_n = (target_sd / a) ** (1 / b)
        return "> 1500" if np.isnan(calc_n) or calc_n > 10000 else f"N ≈ {int(np.round(calc_n / 5) * 5)}"
    except: return "N/A"

