def apply_clinical_boundary_noise(X_data, y_data, noise_level=0.15):
    """Simulates clinical diagnostic ambiguity by flipping labels close to the decision boundary."""
    clf_probe = LogisticRegression(max_iter=1000, class_weight='balanced', random_state=42)
    clf_probe.fit(X_data, y_data)
    probs = clf_probe.predict_proba(X_data)[:, 1]

    boundary_distance = np.abs(probs - 0.5)
    n_flip = int(len(y_data) * noise_level)
    ambiguous_idx = np.argsort(boundary_distance)[:n_flip]

    y_noisy = y_data.copy()
    y_noisy[ambiguous_idx] = 1 - y_noisy[ambiguous_idx]
    return y_noisy

def compute_metrics_bundle(y_true, y_prob):
    """Calculates comprehensive classification, calibration, and discrimination metrics."""
    y_pred = (y_prob >= 0.5).astype(int)
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()

    try: auc_val = roc_auc_score(y_true, y_prob) if len(np.unique(y_true)) > 1 else np.nan
    except Exception: auc_val = np.nan

    return {
        'AUC': auc_val,
        'Brier': brier_score_loss(y_true, y_prob),
        'F1': f1_score(y_true, y_pred, zero_division=0),
        'Sens': tp / (tp + fn + 1e-9),
        'Spec': tn / (tn + fp + 1e-9)
    }

def get_classifier(model_name, seed):
    """Standardized classifiers across different learning paradigms to isolate variance."""
    if model_name == 'LogisticRegression':
        return LogisticRegression(max_iter=1000, class_weight='balanced', random_state=seed)
    elif model_name == 'XGBoost':
        return XGBClassifier(n_estimators=100, max_depth=3, learning_rate=0.05, eval_metric='logloss', random_state=seed)
    else:
        return RandomForestClassifier(n_estimators=100, class_weight='balanced', random_state=seed)

